import (
	"encoding/binary"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// This opt-in oracle reads private native checkpoints without retaining them.
func TestClassWorkspaceInitializerNativeOracle(t *testing.T) {
	trace, digestPath := os.Getenv("UNFAIRPLAY_CLASS_SCHEDULE_ORACLE"), os.Getenv("UNFAIRPLAY_CLASS_DIGEST_ORACLE")
	if trace == "" || digestPath == "" {
		t.Skip("native workspace and digest checkpoints not configured")
	}
	blob, err := os.ReadFile(trace)
	if err != nil {
		t.Fatal(err)
	}
	defer clear(blob)
	digest, err := os.ReadFile(digestPath)
	if err != nil {
		t.Fatal(err)
	}
	defer clear(digest)
	if len(digest) != 20 {
		t.Fatal("invalid digest size")
	}
	var rows []struct {
		PC     uint64
		Matrix []byte
	}
	if err := json.Unmarshal(blob, &rows); err != nil {
		t.Fatal(err)
	}
	checkpoints := []uint64{0x100288228, 0x1002884b8}
	for pass, pc := range checkpoints {
		found := false
		for _, row := range rows {
			if row.PC != pc {
				continue
			}
			if found || len(row.Matrix) < 38 {
				t.Fatal("invalid initializer checkpoint")
			}
			found = true
			state := classWorkspaceInitialize(binary.BigEndian.Uint16(digest[16+pass*2 : 18+pass*2]))
			if state.Seed != binary.LittleEndian.Uint16(row.Matrix[:2])-classWorkspacePeerBias {
				t.Fatalf("pass %d header differs", pass)
			}
			for i := range 9 {
				if state.Product[i] != binary.LittleEndian.Uint16(row.Matrix[2+i*2:])-classWorkspaceSampleCutoff || state.Current[i] != binary.LittleEndian.Uint16(row.Matrix[20+i*2:])-classWorkspacePeerBias {
					t.Fatalf("pass %d cell %d differs", pass, i)
				}
			}
		}
		if !found {
			t.Fatalf("missing pass %d checkpoint", pass)
		}
	}
	t.Log("native workspace initializers match")
}

// Native boundary captures are generated by perturbing both digest words at
// the constructor boundary. They remain external and are never committed.
func TestClassWorkspaceInitializerNativeBoundaries(t *testing.T) {
	dir := os.Getenv("UNFAIRPLAY_CLASS_BOUNDARY_DIRECTORY")
	if dir == "" {
		t.Skip("native initializer boundary controls not configured")
	}
	controls := []struct {
		name string
		word uint16
	}{{"0", 0}, {"1", 1}, {"0x3fff", 0x3fff}, {"0x4000", 0x4000}, {"0x7ffe", 0x7ffe}, {"0x7fff", 0x7fff}, {"0x8000", 0x8000}, {"0xffff", 0xffff}}
	for _, tc := range controls {
		t.Run(tc.name, func(t *testing.T) {
			blob, err := os.ReadFile(filepath.Join(dir, "sidb-init-boundary-"+tc.name+".json"))
			if err != nil {
				t.Fatal(err)
			}
			defer clear(blob)
			var rows []struct {
				PC     uint64
				Matrix []byte
			}
			if err := json.Unmarshal(blob, &rows); err != nil {
				t.Fatal(err)
			}
			if len(rows) != 2 {
				t.Fatalf("got %d initializer boundaries", len(rows))
			}
			for pass, row := range rows {
				if len(row.Matrix) < 38 {
					t.Fatal("truncated initializer")
				}
				expectedPC := []uint64{0x100288228, 0x1002884b8}[pass]
				if row.PC != expectedPC {
					t.Fatal("unexpected initializer boundary")
				}
				state := classWorkspaceInitialize(tc.word)
				if state.Seed != binary.LittleEndian.Uint16(row.Matrix)-classWorkspacePeerBias {
					t.Fatalf("pass %d header differs", pass)
				}
				for i := range 9 {
					if state.Product[i] != binary.LittleEndian.Uint16(row.Matrix[2+2*i:])-classWorkspaceSampleCutoff || state.Current[i] != binary.LittleEndian.Uint16(row.Matrix[20+2*i:])-classWorkspacePeerBias {
						t.Fatalf("pass %d cell %d differs", pass, i)
					}
				}
			}
		})
	}
}
