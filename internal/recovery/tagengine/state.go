package tagengine

import "math/bits"

// initialState returns the decoded bytes prepared for mixing. The caller supplies
// the six-byte hardware identity validated by the constructor entry point.
func initialState(hardware []byte) [256]byte {
	var state [256]byte
	for i := range state {
		q, r := i/6, i%6
		shift := ((q ^ ((q & 2) << 1)) + 5*q*r) & 7
		state[i] = bits.RotateLeft8(hardware[r], shift)
	}
	return state
}

// mixRounds returns the number of mixing iterations for a six-byte identity.
func mixRounds(hardware []byte) int {
	return 2569 + 256*int(hardware[3]%7)
}

