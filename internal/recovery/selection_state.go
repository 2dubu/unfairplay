func selectionStateRound(input, key [16]byte, mix bool) (output [16]byte) {
	shift := [16]byte{0, 5, 10, 15, 4, 9, 14, 3, 8, 13, 2, 7, 12, 1, 6, 11}
	var substituted [16]byte
	for target, source := range shift {
		substituted[target] = frameSBox[input[source]^key[source]]
	}
	if !mix {
		return substituted
	}
	for column := range 4 {
		offset := column * 4
		a, b, c, d := substituted[offset], substituted[offset+1], substituted[offset+2], substituted[offset+3]
		output[offset] = frameGFMul(2, a) ^ frameGFMul(3, b) ^ c ^ d
		output[offset+1] = a ^ frameGFMul(2, b) ^ frameGFMul(3, c) ^ d
		output[offset+2] = a ^ b ^ frameGFMul(2, c) ^ frameGFMul(3, d)
		output[offset+3] = frameGFMul(3, a) ^ b ^ c ^ frameGFMul(2, d)
	}
	return output
}

func transformSelectionStateSlot(slot int, input [16]byte) ([16]byte, error) {
	if slot < 0 || slot >= selectionStateSlotCount {
		return [16]byte{}, fmt.Errorf("selection state slot %d is outside 0..%d", slot, selectionStateSlotCount-1)
	}
	return transformSelectionStateSlotWithKey(slot, input, selectionStateFirstRoundKeys[slot])
}

func transformSelectionStateSlotWithKey(slot int, input, firstRoundKey [16]byte) ([16]byte, error) {
	var output [16]byte
	if slot < 0 || slot >= selectionStateSlotCount {
		return output, fmt.Errorf("selection state slot %d is outside 0..%d", slot, selectionStateSlotCount-1)
	}
	output = selectionStateRound(input, firstRoundKey, true)
	for _, key := range selectionStateSharedRoundKeys[:len(selectionStateSharedRoundKeys)-1] {
		output = selectionStateRound(output, key, true)
	}
	output = selectionStateRound(output, selectionStateSharedRoundKeys[len(selectionStateSharedRoundKeys)-1], false)
	for index := range output {
		output[index] ^= selectionStateOutputMask[index]
	}
	return output, nil
}

// transformSelectionStateSlots maps a raw 192- or 224-byte source to all
// fourteen candidate enrollment slots. A 192-byte source has twelve real
// candidates; the two padded outputs are retained only to match native state.
func transformSelectionStateSlots(source []byte) ([selectionStateSlotCount][16]byte, int, error) {
	var output [selectionStateSlotCount][16]byte
	if len(source) != 192 && len(source) != 224 {
		return output, 0, fmt.Errorf("selection state source has %d bytes, want 192 or 224", len(source))
	}
	realSlots := len(source) / 16
	var previousOutput, previousBaseline [16]byte
	for slot := range selectionStateSlotCount {
		var input [16]byte
		if slot < realSlots {
			copy(input[:], source[slot*16:(slot+1)*16])
		}
		firstRoundKey := selectionStateFirstRoundKeys[slot]
		if slot != 0 {
			for index := range firstRoundKey {
				firstRoundKey[index] ^= previousOutput[index] ^ previousBaseline[index]
			}
		}
		value, err := transformSelectionStateSlotWithKey(slot, input, firstRoundKey)
		if err != nil {
			return output, 0, err
		}
		baseline, err := transformSelectionStateSlot(slot, [16]byte{})
		if err != nil {
			return output, 0, err
		}
		output[slot] = value
		previousOutput, previousBaseline = value, baseline
	}
	return output, realSlots, nil
}
