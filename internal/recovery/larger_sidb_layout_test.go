func TestSyntheticSIDBLayoutAndProjection(t *testing.T) {
	const bodyBytes = 64 << 10
	data, hardware, layout := syntheticNativeSIDB(t, bodyBytes)
	_, actual, iterations, err := deriveNativeSelectionSource(data, hardware)
	if err != nil || actual != layout || actual.PayloadBytes != bodyBytes || iterations != actual.OuterIterations {
		t.Fatalf("synthetic layout: %+v, %v", actual, err)
	}
	projected, err := decodeSelectionSIDBContainerWithLayout(data, layout)
	if err != nil {
		t.Fatal(err)
	}
	for i, value := range projected {
		if value != data[layout.PayloadOffset+i]^selectionSIDBInputMask[i%16] {
			t.Fatalf("projection mismatch at %d", i)
		}
	}
	data[len(data)-1] ^= 1
	projected2, err := decodeSelectionSIDBContainerWithLayout(data, layout)
	if err != nil || !bytes.Equal(projected, projected2) {
		t.Fatal("trailer affected projection")
	}
	invalidLayout := layout
	invalidLayout.PayloadBytes += selectionSIDBBlockBytes
	if _, err := decodeSelectionSIDBContainerWithLayout(data, invalidLayout); err == nil {
		t.Fatal("accepted body extending into trailer")
	}
	if _, err := decodeSelectionSIDBContainerWithLayout(data[:len(data)-1], layout); err == nil {
		t.Fatal("accepted truncated trailer")
	}
	bad := append([]byte(nil), data...)
	bad[3] ^= 1
	if _, _, _, err := deriveNativeSelectionSource(bad, hardware); err == nil {
		t.Fatal("accepted unknown version")
	}
}

func TestDynamicSIDBCipherRoundTrip(t *testing.T) {
	key := [16]byte{1, 3, 5, 7}
	cipher, err := aes.NewCipher(key[:])
	if err != nil {
		t.Fatal(err)
	}
	for _, size := range []int{selectionSIDBPayloadBytes, 64 << 10} {
		plain, input := make([]byte, size), make([]byte, size)
		for i := range plain {
			plain[i] = byte(i*73 + i/16)
		}
		for offset := 0; offset < size; offset += 16 {
			var pre, raw [16]byte
			for i := range pre {
				pre[i] = plain[offset+i] ^ selectionSIDBOutputMask[i]
				if offset > 0 {
					pre[i] ^= input[offset-16+i] ^ selectionSIDBChainMask[i]
				}
			}
			cipher.Encrypt(raw[:], pre[:])
			for i := range raw {
				input[offset+i] = raw[i] ^ selectionSIDBInputMask[i]
			}
		}
		decoded, err := decryptSelectionSIDBPayloadDynamic(input, key)
		if err != nil || !bytes.Equal(decoded, plain) {
			t.Fatalf("round trip size %d: %v", size, err)
		}
	}
	for _, size := range []int{0, 15, maximumSelectionSIDBPayloadBytes + 16} {
		if _, err := decryptSelectionSIDBPayloadDynamic(make([]byte, size), key); err == nil {
			t.Fatalf("accepted body size %d", size)
		}
	}
}

func TestLargerSIDBSourceContinuation(t *testing.T) {
	var state outerTableRoundState
	for i := range state.Source {
		state.Source[i] = byte(i*3 + 1)
	}
	for i := range state.Writer {
		state.Writer[i] = byte(i*5 + 2)
	}
	for i := range state.Tail {
		state.Tail[i] = byte(i*7 + 3)
	}
	source, err := selectionSourceFromOuterState(&state, 256)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(source[:224], state.Source[:]) || !bytes.Equal(source[224:232], state.Writer[132:140]) || !bytes.Equal(source[232:256], state.Tail[40:64]) {
		t.Fatal("incorrect source continuation")
	}
	layouts, err := selectionSourceLayouts(source)
	if err != nil || len(layouts) != 2 || !bytes.Equal(layouts[0], source[32:]) || !bytes.Equal(layouts[1], source[32:224]) {
		t.Fatal("incorrect larger source layout")
	}
	states, count, err := transformSelectionStateSlots(layouts[0])
	if err != nil || count != 14 {
		t.Fatal("incorrect state count")
	}
	altered := append([]byte(nil), source...)
	altered[224] ^= 1
	changed, _, err := transformSelectionStateSlots(altered[32:])
	if err != nil || changed[12] == states[12] {
		t.Fatal("slot 12 did not use continuation")
	}
	candidates, err := enrollmentKeyCandidates(layouts[0])
	if err != nil || len(candidates) != 14 || candidates[12].State != states[12] {
		t.Fatal("missing slot 12 candidate")
	}
	if _, err := selectionSourceFromOuterState(&state, 255); err == nil {
		t.Fatal("accepted unsupported source length")
	}
}

// syntheticNativeSIDB finds an independently generated byte pattern whose
// native codec stop falls within the bounded codec buffer. Its body is then
// sized to the requested aligned length without changing the codec bytes.
func syntheticNativeSIDB(t *testing.T, bodyBytes int) ([]byte, []byte, currentSIDBLayout) {
	t.Helper()
	hardware := []byte{2, 19, 36, 53, 70, 87}
	for seed := 0; seed < 64; seed++ {
		data := make([]byte, 4+372+bodyBytes+selectionSIDBExtendedTrailerBytes)
		binary.BigEndian.PutUint32(data, currentSIDBContainerVersion)
		for i := 4; i < len(data); i++ {
			data[i] = byte(i*37 + seed*19 + 11)
		}
		_, layout, _, _ := deriveNativeSelectionSource(data, hardware)
		if layout.CodecBytes == 0 {
			continue
		}
		data = data[:4+layout.CodecBytes+bodyBytes+selectionSIDBExtendedTrailerBytes]
		_, checked, _, err := deriveNativeSelectionSource(data, hardware)
		if err == nil && checked.CodecBytes == layout.CodecBytes {
			return data, hardware, checked
		}
	}
	t.Fatal("synthetic native codec did not reach a bounded exit")
	return nil, nil, currentSIDBLayout{}
}

func TestNativeSIDBContentDependentBoundary(t *testing.T) {
	data, hardware, base := syntheticNativeSIDB(t, selectionSIDBPayloadBytes)
	// This invented codec and hardware reached the same native dispatch at 493 iterations.
	if base.CodecBytes != 45 || base.OuterIterations != 493 {
		t.Fatalf("synthetic native codec boundary changed: %d/%d", base.CodecBytes, base.OuterIterations)
	}
	source, layout, iterations, err := deriveNativeSelectionSource(data, hardware)
	if err != nil || layout != base || iterations != 11*layout.CodecBytes-2 || len(source) != 256 {
		t.Fatalf("native source geometry: %+v %d %v", layout, iterations, err)
	}
	changed := false
	for offset := 4; offset < 17; offset++ {
		mutated := append([]byte(nil), data...)
		mutated[offset] ^= 1
		_, other, _, _ := deriveNativeSelectionSource(mutated, hardware)
		if other.CodecBytes != 0 && other.CodecBytes != layout.CodecBytes {
			changed = true
			break
		}
	}
	if !changed {
		t.Fatal("same-length codec mutations did not change the native stop")
	}
	badVersion := append([]byte(nil), data...)
	badVersion[3] ^= 1
	if _, _, _, err := deriveNativeSelectionSource(badVersion, hardware); err == nil {
		t.Fatal("accepted unknown version")
	}
	if _, _, _, err := deriveNativeSelectionSource(data, hardware[:5]); err == nil {
		t.Fatal("accepted invalid hardware length")
	}
	if _, _, _, err := deriveNativeSelectionSource(data[:len(data)-1], hardware); err == nil {
		t.Fatal("accepted an unaligned truncated body")
	}
}
