//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
)

func constants(path, typeName, lastName string, excludeLast bool) ([]string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, err
	}
	var result []string
	active := false
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.CONST {
			continue
		}
		for _, specification := range general.Specs {
			value := specification.(*ast.ValueSpec)
			if value.Type != nil {
				identifier, ok := value.Type.(*ast.Ident)
				active = ok && identifier.Name == typeName
			}
			if !active {
				continue
			}
			for _, name := range value.Names {
				if name.Name == lastName {
					if !excludeLast {
						result = append(result, name.Name)
					}
					return result, nil
				}
				result = append(result, name.Name)
			}
		}
	}
	return nil, fmt.Errorf("did not find %s through %s in %s", typeName, lastName, path)
}

func main() {
	arguments := os.Args[1:]
	if len(arguments) != 0 && arguments[0] == "--" {
		arguments = arguments[1:]
	}
	if len(arguments) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen_opcodes COMPACT_KERNEL COMPACT_CFG OUTPUT")
		os.Exit(2)
	}
	opcodes, err := constants(arguments[0], "compactOpcode", "compactOpcodeCount", true)
	if err != nil {
		panic(err)
	}
	terminators, err := constants(arguments[1], "compactBlockTerminator", "compactBlockStopDirect", false)
	if err != nil {
		panic(err)
	}
	conditions, err := constants(arguments[1], "compactCondition", "compactConditionLE", false)
	if err != nil {
		panic(err)
	}
	var source bytes.Buffer
	source.WriteString("// Code generated by gen_opcodes.go; DO NOT EDIT.\npackage main\n\n")
	writeMap := func(name string, values []string) {
		fmt.Fprintf(&source, "var %s = map[string]uint16{\n", name)
		for index, value := range values {
			fmt.Fprintf(&source, "\t%q: %d,\n", value, index)
		}
		source.WriteString("}\n\n")
	}
	writeMap("runtimeCompactOpcodeNumbers", opcodes)
	writeMap("runtimeCompactTerminatorNumbers", terminators)
	writeMap("runtimeCompactConditionNumbers", conditions)
	fmt.Fprintf(&source, "const runtimeCompactOpcodeCount = %d\n", len(opcodes))
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(arguments[2], formatted, 0o644); err != nil {
		panic(err)
	}
}
